"""Unity app codes that are not one of the seven apparatus fault types (#284).

``vocab.APP_FAULT_CODE_TYPES`` maps the app codes that state one of the seven fault types
of Common procedures section 2 (item 6). Every other code-shaped string literal in the app
runtime (``unity/Assets/ExperimentApp/Runtime/**/*.cs``) is listed here as reviewed and
not applicable: other faults (session, journal, configuration, binding, timing, transport),
refusal and status codes, and the few literals in that shape that are not codes at all.
``vocab.fault_type`` classifies them as ``other``; a technical fault is a technical failure
whatever its type (``scoring.is_technical_failure``).

``tests/analysis/test_app_fault_codes.py`` scans the runtime for literals matching
:data:`APP_CODE_LITERAL_RE` and fails on a code in neither set. To classify a new app code,
add it to ``vocab.APP_FAULT_CODE_TYPES`` when it states one of the seven faults, else
here. Both sets also hold the codes of Unity pull requests queued for merge (scanned on a
local merge of the queue), so a listed or mapped code may be absent from a given tree.
Codes the app composes at run time (``"JOIN_" + ...`` startup status reports and
missing-authority names; ``"LESSON_PANEL_" + reason`` in a queued change) are not
scanned; they classify as ``other``.
"""

